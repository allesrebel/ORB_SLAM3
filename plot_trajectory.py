#!/usr/bin/env python3
import sys
import pandas as pd
import matplotlib.pyplot as plt
import argparse
import os

def plot_trajectory(csv_file, output_png):
    """
    Reads trajectory_pair.csv which contains associated ground truth and aligned 
    estimated trajectories, and saves a 2D top-down (x-y) plot as a PNG.
    """
    df = pd.read_csv(csv_file)
    
    if 'x_gt' not in df.columns or 'x_est' not in df.columns:
        print("Error: CSV must contain 'x_gt', 'y_gt', 'x_est', 'y_est' columns.")
        return

    # Set up the plot
    plt.figure(figsize=(10, 8))
    plt.title('Trajectory Comparison', fontsize=16)
    
    # Plot Ground Truth
    plt.plot(df['x_gt'], df['y_gt'], 'k-', label='Ground Truth', linewidth=2, alpha=0.8)
    
    # Plot Aligned Estimate
    plt.plot(df['x_est'], df['y_est'], 'b-', label='ORB-SLAM3 Estimate', linewidth=2, alpha=0.8)

    plt.xlabel('X [m]', fontsize=12)
    plt.ylabel('Y [m]', fontsize=12)
    plt.grid(True, linestyle='--', alpha=0.6)
    plt.legend(fontsize=12)
    plt.axis('equal')
    
    # Save the plot
    plt.savefig(output_png, dpi=300, bbox_inches='tight')
    print(f"Successfully saved trajectory plot to: {output_png}")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Plot ORB-SLAM3 Trajectory from trajectory_pair.csv")
    parser.add_argument("csv_file", help="Path to trajectory_pair.csv generated by evaluate_ate_scale.py")
    parser.add_argument("--output", "-o", default="trajectory_plot.png", help="Output PNG file path")
    args = parser.parse_args()
    
    if not os.path.exists(args.csv_file):
        sys.exit(f"CSV file not found: {args.csv_file}")
        
    plot_trajectory(args.csv_file, args.output)
